// Command gen writes html/tags.go and attr/attrs.go.
// Run it from the module root: go generate ./...
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

var tags = strings.Fields(`
a abbr address area article aside audio b base bdi bdo blockquote body br
button canvas caption cite code col colgroup data datalist dd del details
dfn dialog div dl dt em embed fieldset figcaption figure footer form h1 h2
h3 h4 h5 h6 head header hgroup hr html i iframe img input ins kbd label
legend li link main map mark menu meta meter nav noscript object ol
optgroup option output p picture pre progress q rp rt ruby s samp script
search section select slot small source span strong style sub summary sup
table tbody td template textarea tfoot th thead time title tr track u ul
var video wbr`)

// class and data are hand-written in attr/custom.go.
var textAttrs = strings.Fields(`
accept alt autocomplete charset cols colspan content crossorigin dir
download enctype for form height hreflang http-equiv id integrity lang list
loading max maxlength method min minlength name pattern placeholder
referrerpolicy rel role rows rowspan sizes srcset step style tabindex
target title type value width`)

var urlAttrs = strings.Fields(`action cite formaction href poster src`)

var boolAttrs = strings.Fields(`
async autofocus checked defer disabled hidden multiple novalidate open
readonly required selected`)

var special = map[string]string{"html": "HTML", "id": "ID", "http-equiv": "HTTPEquiv"}

func ident(s string) string {
	if v, ok := special[s]; ok {
		return v
	}
	parts := strings.Split(s, "-")
	for i, p := range parts {
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}

func write(path string, src []byte) {
	out, err := format.Source(src)
	if err != nil {
		log.Fatalf("%s: %v\n%s", path, err, src)
	}
	if err := os.WriteFile(path, out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen; DO NOT EDIT.\n\npackage html\n\nimport \"markup\"\n\n")
	for _, t := range tags {
		fmt.Fprintf(&b, "// %s returns a <%s> element.\nfunc %[1]s(items ...markup.Node) *markup.Element { return markup.Tag(%q, items...) }\n\n", ident(t), t, t)
	}
	write("html/tags.go", b.Bytes())

	b.Reset()
	b.WriteString("// Code generated by internal/gen; DO NOT EDIT.\n\npackage attr\n\nimport \"markup\"\n\n")
	for _, a := range textAttrs {
		fmt.Fprintf(&b, "// %s returns the %s attribute.\nfunc %[1]s(v string) markup.Attr { return markup.NewAttr(%q, v) }\n\n", ident(a), a, a)
	}
	for _, a := range urlAttrs {
		fmt.Fprintf(&b, "// %s returns the %s attribute. Unsafe URL schemes render as \"#unsafe\".\nfunc %[1]s(v string) markup.Attr { return markup.URL(%q, v) }\n\n", ident(a), a, a)
	}
	for _, a := range boolAttrs {
		fmt.Fprintf(&b, "// %s returns the boolean %s attribute.\nfunc %[1]s() markup.Attr { return markup.Bool(%q) }\n\n", ident(a), a, a)
	}
	write("attr/attrs.go", b.Bytes())
}
